"""The Go module and npm package assembled for a release."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from bbfmodels import sources
from bbfmodels.distribute import GO_MODULE, go_module, go_package_name, npm_package
from bbfmodels.generate import PACKAGES


def _all_cached() -> None:
    missing = [n for n in PACKAGES.values() if not (sources.cache_dir() / n).exists()]
    if missing:
        pytest.skip(f"{len(missing)} documents are not in the cache; run 'bbfmodels fetch'")


def test_go_package_names() -> None:
    assert go_package_name("bbfmodels.tr181_usp") == "tr181usp"
    assert go_package_name("bbfmodels.tr104_1") == "tr1041"


def test_go_module(tmp_path: Path) -> None:
    _all_cached()
    written = go_module(tmp_path, "9.9.9")
    assert (tmp_path / "go.mod").read_text() == f"module {GO_MODULE}\n\ngo 1.22\n"
    assert {p.name for p in tmp_path.iterdir()} >= {
        "go.mod",
        "README.md",
        "LICENSE",
        "NOTICE",
        "tr181usp",
        "tr098",
    }
    assert "This is bbfmodels 9.9.9." in (tmp_path / "README.md").read_text()
    assert (tmp_path / "tr181usp" / "doc.go").read_text().startswith("// Package tr181usp holds")
    assert len(written) > 400
    # a second run replaces, it does not accumulate
    go_module(tmp_path, "9.9.9")
    assert len({p.name for p in (tmp_path / "tr098").iterdir()}) == len(
        [p for p in written if p.parent.name == "tr098"]
    )


def test_npm_package(tmp_path: Path) -> None:
    _all_cached()
    npm_package(tmp_path, "9.9.9")
    manifest = json.loads((tmp_path / "package.json").read_text())
    assert manifest["name"] == "@ispx/bbfmodels" and manifest["version"] == "9.9.9"
    assert manifest["exports"]["./tr181_usp"] == {"types": "./tr181_usp.d.ts"}
    assert len(manifest["exports"]) == len(PACKAGES)
    assert (tmp_path / "tr181_usp.d.ts").read_text().startswith("// Generated by bbfmodels")
    assert {p.name for p in tmp_path.iterdir()} >= {
        "package.json",
        "README.md",
        "LICENSE",
        "NOTICE",
    }
    assert "This is bbfmodels 9.9.9." in (tmp_path / "README.md").read_text()
