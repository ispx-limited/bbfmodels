"""Go types emitted from the IR, checked with the Go toolchain when present."""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

from bbfmodels import sources
from bbfmodels.golang import go_package, write_go_package
from bbfmodels.parser import parse_file

FIXTURES = Path(__file__).parent / "fixtures"


@pytest.fixture(scope="module")
def files() -> dict[str, str]:
    return go_package(parse_file(FIXTURES / "mini-cwmp-full.xml"), "mini")


def test_files_and_structs(files: dict[str, str]) -> None:
    assert set(files) == {"doc.go", "device.go", "radio.go", "config.go"}
    assert files["doc.go"].startswith("// Package mini holds the Device_vendor-1.2:2.0 data model")
    device = files["device.go"]
    assert device.startswith(
        "// Code generated by bbfmodels from mini-1-0-0-cwmp-full.xml. DO NOT EDIT."
    )
    assert "\npackage mini\n" in device and 'import "time"' not in device
    assert "type Device struct {" in device
    assert '\tRadio map[int]*Radio `json:"Radio,omitempty" bbf:"Device.Radio."`\n' in device
    assert '\tConfig map[int]*Config `json:"Config,omitempty" bbf:"Device.Config."`\n' in device
    radio = files["radio.go"]
    assert "// Radio is Device.Radio.{i}.\n//\n// One radio.\n" in radio
    assert '\tEnable *bool `json:"Enable,omitempty" bbf:"Device.Radio.{i}.Enable"`\n' in radio
    assert '\tChannel *uint32 `json:"Channel,omitempty" bbf:"Device.Radio.{i}.Channel"`\n' in radio
    assert '\tStandards []string `json:"Standards,omitempty"' in radio
    assert '\tN11kEnable *bool `json:"11kEnable,omitempty"' in radio
    assert "\t// readWrite\n\tMode *string" in radio


def test_descriptions_off_and_bad_package_name() -> None:
    doc = parse_file(FIXTURES / "mini-cwmp-full.xml")
    bare = go_package(doc, "mini", descriptions=False)
    assert "One radio." not in bare["radio.go"] and "// readWrite" in bare["radio.go"]
    with pytest.raises(ValueError, match="Go package name"):
        go_package(doc, "Mini-Models")


def test_commands_events_and_time() -> None:
    files = go_package(parse_file(FIXTURES / "mini-usp-full.xml"), "miniusp")
    device = files["device.go"]
    assert "type Device_TraceRoute_Input struct {" in device
    assert "type Device_TraceRoute_Output_RouteHops struct {" in device
    assert (
        '\tRouteHops map[int]*Device_TraceRoute_Output_RouteHops `json:"RouteHops,omitempty"'
        in device
    )
    assert "type Device_Boot_Event struct {" in device
    assert "\t// mandatory\n\tHost *string" in device
    assert 'import "time"' not in device


@pytest.mark.skipif(
    shutil.which("go") is None or shutil.which("gofmt") is None, reason="no Go toolchain"
)
def test_tr181_passes_gofmt_vet_and_round_trips(tmp_path: Path) -> None:
    name = "tr-181-2-21-0-usp-full.xml"
    source = sources.cache_dir() / name
    if not source.exists():
        pytest.skip(f"{name} is not in the cache; run 'bbfmodels fetch'")
    write_go_package(parse_file(source), "tr181usp", tmp_path / "tr181usp")
    (tmp_path / "go.mod").write_text("module example.com/check\n\ngo 1.22\n")
    (tmp_path / "check_test.go").write_text(
        """package check

import (
\t"encoding/json"
\t"testing"

\t"example.com/check/tr181usp"
)

func TestRoundTrip(t *testing.T) {
\tin := `{"WiFi":{"Radio":{"1":{"Enable":true,"Channel":36,"SupportedFrequencyBands":["2.4GHz","5GHz"]}}}}`
\tvar d tr181usp.Device
\tif err := json.Unmarshal([]byte(in), &d); err != nil {
\t\tt.Fatal(err)
\t}
\tif *d.WiFi.Radio[1].Channel != 36 || len(d.WiFi.Radio[1].SupportedFrequencyBands) != 2 {
\t\tt.Fatalf("unexpected %+v", d)
\t}
\tout, _ := json.Marshal(d)
\tvar back tr181usp.Device
\tif err := json.Unmarshal(out, &back); err != nil || *back.WiFi.Radio[1].Channel != 36 {
\t\tt.Fatal("round trip lost the channel")
\t}
}
"""
    )
    unformatted = subprocess.run(
        ["gofmt", "-l", "."], cwd=tmp_path, capture_output=True, text=True, check=True
    )
    assert unformatted.stdout == "", unformatted.stdout
    subprocess.run(["go", "vet", "./..."], cwd=tmp_path, check=True, capture_output=True)
    subprocess.run(["go", "test", "./..."], cwd=tmp_path, check=True, capture_output=True)
