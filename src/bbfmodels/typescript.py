"""TypeScript declarations for a document's model, emitted from the IR.

One ``.d.ts`` module per document: an interface per object named like the
generated Python class (``WiFi_Radio``), an optional property per
parameter, a child object as a property of its interface type, a table as
``Instances<Child>`` (a record keyed by instance number), and a template
literal index signature that admits ``X_`` vendor members as ``unknown``.
Command inputs and outputs and event payloads are interfaces too, and the
``Commands`` and ``Events`` interfaces map each path to them.

An enumeration is ``Open<"a" | "b">``, which is ``"a" | "b" | (string & {})``:
the editor completes the Forum's values and any other string still type
checks, the same trade the Python models make. The emitter reads the IR
directly rather than converting the JSON Schema, which would close the
union.
"""

from __future__ import annotations

import json
import re

from bbfmodels.describe import render
from bbfmodels.generate import class_name
from bbfmodels.ir import Arguments, BaseType, DataType, Document, Model, Object, Parameter, Syntax
from bbfmodels.paths import member_name

_PRELUDE = """\
/** The Forum's values complete in the editor; any other string still type checks. */
export type Open<T extends string> = T | (string & {});
/** A multi-instance object: its instances keyed by instance number. */
export type Instances<T> = Record<number, T>;
/** A vendor extension member the model does not define. */
export type Vendor = unknown;
"""

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def declarations(doc: Document, *, descriptions: bool = True) -> str:
    """The TypeScript declarations of a document's one model."""
    if len(doc.models) != 1:
        raise ValueError(
            f"{doc.file or doc.spec} has {len(doc.models)} models; one module per model"
        )
    model = doc.models[0]
    root_obj = next(iter(model.objects.values()))
    root = root_obj.name
    em = _Emitter(model, root, descriptions, doc.data_types)
    out = [
        f"// Generated by bbfmodels from {doc.file or doc.spec}. Do not edit: change the\n"
        "// generator or the source document and regenerate.\n\n",
        _PRELUDE,
        "\n",
    ]
    commands: list[str] = []
    events: list[str] = []
    for obj in model.objects.values():
        out.append(em.interface(class_name(obj, root), obj, obj.path))
        em.arguments(obj, root, out, commands, events)
    root_name = class_name(root_obj, root)
    if root_obj.multi_instance:
        out.append(f"/** The model's root, a table of {root_obj.path} instances. */\n")
        out.append(f"export type Root = Instances<{root_name}>;\n\n")
    else:
        out.append(f"/** The model's root object, {root_obj.path} */\n")
        out.append(f"export type Root = {root_name};\n\n")
    out.append("/** Every command by path, with its input and output. */\n")
    out.append("export interface Commands {\n" + "".join(commands) + "}\n\n")
    out.append("/** Every event by path, with its payload. */\n")
    out.append("export interface Events {\n" + "".join(events) + "}\n")
    return "".join(out)


def _prop(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name)


class _Emitter:
    def __init__(
        self, model: Model, root: str, descriptions: bool, data_types: dict[str, DataType]
    ) -> None:
        self.model = model
        self.root = root
        self.descriptions = descriptions
        self.data_types = data_types
        self.owner = ""

    def doc(self, text: str, indent: str = "") -> str:
        if not self.descriptions or not text:
            return ""
        safe = text.replace("*/", "* /")
        lines = safe.split("\n")
        if len(lines) == 1:
            return f"{indent}/** {lines[0]} */\n"
        body = "".join(f"{indent} * {line}".rstrip() + "\n" for line in lines)
        return f"{indent}/**\n" + body + f"{indent} */\n"

    def interface(
        self,
        name: str,
        obj: Object,
        path: str,
        children: list[tuple[str, str, bool]] | None = None,
    ) -> str:
        if children is None:
            children = [
                (c.name, class_name(c, self.root), c.multi_instance)
                for c in self.model.objects.values()
                if c.parent_path == path
            ]
        self.owner = obj.name
        text = render(obj.description, object=obj.name)
        lines = [self.doc(f"{path}\n\n{text}" if text else path)]
        lines.append(f"export interface {name} {{\n")
        for param in obj.parameters.values():
            lines.append(self.property(param))
        for child_name, child_type, multi in children:
            typ = f"Instances<{child_type}>" if multi else child_type
            lines.append(f"  {_prop(child_name)}?: {typ};\n")
        lines.append("  [vendor: `X_${string}`]: Vendor;\n")
        lines.append("}\n\n")
        return "".join(lines)

    def property(self, param: Parameter) -> str:
        notes = []
        if param.access is not None:
            notes.append(param.access.value)
        if param.status.value != "current":
            notes.append(param.status.value)
        if param.mandatory:
            notes.append("mandatory")
        head = ", ".join(notes)
        text = (
            f"{head}. {param.description}"
            if head and param.description
            else head or param.description
        )
        return self.doc(text, "  ") + f"  {_prop(param.name)}?: {self.type_of(param.syntax)};\n"

    def type_of(self, s: Syntax) -> str:
        base = self.scalar(s)
        return f"{base}[]" if s.list is not None else base

    def scalar(self, s: Syntax) -> str:
        match s.base_type:
            case BaseType.STRING:
                f = s.facets
                if f.enumerations and f.enumeration_ref is None:
                    values = " | ".join(json.dumps(e.value) for e in f.enumerations)
                    return f"Open<{values}>"
                return "string"
            case BaseType.BOOLEAN:
                return "boolean"
            case BaseType.DATE_TIME | BaseType.HEX_BINARY | BaseType.BASE64:
                return "string"
            case _:
                return "number"

    def arguments(
        self, obj: Object, root: str, out: list[str], commands: list[str], events: list[str]
    ) -> None:
        owner = class_name(obj, root)
        for cmd in obj.commands.values():
            base = f"{owner}_{member_name(cmd.name)}"
            path = f"{obj.path}{cmd.name}"
            self.argument_interfaces(f"{base}_Input", f"{path}.Input.", cmd.input, out)
            self.argument_interfaces(f"{base}_Output", f"{path}.Output.", cmd.output, out)
            is_async = str(cmd.is_async).lower()
            commands.append(
                f"  {json.dumps(path)}: {{ input: {base}_Input; output: {base}_Output; "
                f"async: {is_async} }};\n"
            )
        for ev in obj.events.values():
            name = f"{owner}_{member_name(ev.name)}_Event"
            path = f"{obj.path}{ev.name}"
            self.argument_interfaces(name, f"{path}.", ev.arguments, out)
            events.append(f"  {json.dumps(path)}: {name};\n")

    def argument_interfaces(self, name: str, path: str, args: Arguments, out: list[str]) -> None:
        def children_of(rel: str) -> list[tuple[str, str, bool]]:
            found = []
            for child_rel in args.objects:
                parent = child_rel[:-4] if child_rel.endswith("{i}.") else child_rel
                parent = parent.rstrip(".").rpartition(".")[0]
                parent = parent + "." if parent else ""
                if parent == rel:
                    segments = [s for s in child_rel.rstrip(".").split(".") if s != "{i}"]
                    found.append(
                        (segments[-1], f"{name}_{'_'.join(segments)}", child_rel.endswith("{i}."))
                    )
            return found

        for rel, nested in args.objects.items():
            segments = [s for s in rel.rstrip(".").split(".") if s != "{i}"]
            out.append(
                self.interface(f"{name}_{'_'.join(segments)}", nested, path + rel, children_of(rel))
            )
        out.append(
            self.interface(
                name, Object(path=path, parameters=args.parameters), path, children_of("")
            )
        )
