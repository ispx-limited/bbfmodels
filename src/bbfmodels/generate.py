"""Generate a Python package of pydantic models from a document's IR.

One package per document. The root object becomes a class named after it
(``Device``) in a module named after it (``device.py``); every other object
lives in the module of its top-level subtree (``Device.WiFi.*`` in
``wifi.py``) under a class named by its path with the root dropped and the
dots replaced (``WiFi_Radio_Stats``). Children are emitted before their
parents so no module needs a forward reference, and the root module imports
the subtree modules. The IR itself ships in the package as ``ir.json.gz``
so the schema is available for validation without the XML.

Generated code is committed and never edited; a test regenerates it and
fails on any difference.
"""

from __future__ import annotations

import gzip
import keyword
import re
from pathlib import Path

from pydantic import BaseModel

from bbfmodels import __version__
from bbfmodels.ir import BaseType, Document, Model, Object, Parameter

# The documents the shipped packages are generated from.
PACKAGES = {
    "bbfmodels.tr181_cwmp": "tr-181-2-21-0-cwmp-full.xml",
    "bbfmodels.tr181_usp": "tr-181-2-21-0-usp-full.xml",
    "bbfmodels.tr098": "tr-098-1-8-0-full.xml",
}

# Every helper is imported under a leading-underscore alias because a
# parameter may carry the helper's name (TR-181 has one called ``Param``)
# and a class body resolves names against the fields defined above the
# annotation. Forum names never start with an underscore.
_PY_TYPE = {
    BaseType.STRING: "str",
    BaseType.INT: "int",
    BaseType.UNSIGNED_INT: "int",
    BaseType.LONG: "int",
    BaseType.UNSIGNED_LONG: "int",
    BaseType.BOOLEAN: "_Boolean",
    BaseType.DATE_TIME: "_datetime",
    BaseType.HEX_BINARY: "_HexBinary",
    BaseType.BASE64: "_Base64Binary",
    BaseType.DECIMAL: "_Decimal",
}

# Names a field cannot have: the base class uses them, Python reserves them,
# or pydantic reads them from the class body (``Config`` is its legacy
# configuration class, and TR-181 has tables called ``Config``).
_RESERVED = set(dir(BaseModel)) | {"bbf_path", "bbf_package", "Config"} | set(keyword.kwlist)

_HEADER = (
    "# Generated by bbfmodels {version} from {source}. Do not edit: change the\n"
    "# generator or the source document and regenerate.\n"
    "# ruff: noqa\n\n"
)


def generate(doc: Document, package: str, out: Path) -> list[Path]:
    """Write the package for a document's root model into ``out``; returns the files written."""
    model = _root_model(doc)
    root = model.root
    source = doc.file or doc.spec
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    groups: dict[str, list[Object]] = {}
    for obj in model.objects.values():
        groups.setdefault(_group_of(obj, root), []).append(obj)
    modules = _module_names(groups)

    for group, objects in groups.items():
        if group == "":
            continue
        body = _HEADER.format(version=__version__, source=source) + _imports(objects)
        body += "".join(_emit_class(o, root, package, modules, model) for o in _postorder(objects))
        path = out / f"{modules[group]}.py"
        path.write_text(body)
        written.append(path)

    root_objects = groups.get("", [])
    body = _HEADER.format(version=__version__, source=source) + _imports(root_objects)
    body += "".join(f"from {package} import {modules[g]}\n" for g in sorted(groups) if g != "")
    body += "\n"
    body += "".join(_emit_class(o, root, package, modules, model) for o in _postorder(root_objects))
    root_path = out / f"{modules['']}.py"
    root_path.write_text(body)
    written.append(root_path)

    init = (
        f'"""{model.name} from {source}.\n\n'
        f"Generated by bbfmodels {__version__}. Do not edit: change the generator or the\n"
        f"source document and regenerate. ``schema()`` loads the IR the models were\n"
        f'generated from, for validation and descriptions.\n"""\n\n'
        f"from bbfmodels.model import load_schema\n"
        f"from {package}.{modules['']} import {root}\n\n"
        f'SOURCE = "{source}"\n'
        f'SPEC = "{doc.spec}"\n'
        f'MODEL = "{model.name}"\n\n\n'
        f"def schema():  # type: ignore[no-untyped-def]\n"
        f"    return load_schema(__name__)\n\n\n"
        f'__all__ = ["{root}", "MODEL", "SOURCE", "SPEC", "schema"]\n'
    )
    init_path = out / "__init__.py"
    init_path.write_text(init)
    written.append(init_path)

    ir_path = out / "ir.json.gz"
    ir_path.write_bytes(gzip.compress(doc.model_dump_json(exclude_defaults=True).encode(), mtime=0))
    written.append(ir_path)
    return written


def _root_model(doc: Document) -> Model:
    roots = [m for m in doc.models if not m.is_service]
    if len(roots) != 1:
        raise ValueError(
            f"{doc.file or doc.spec} has {len(roots)} root models; "
            "one package is generated per root model"
        )
    return roots[0]


def _group_of(obj: Object, root: str) -> str:
    segments = [s for s in obj.path.rstrip(".").split(".") if s != "{i}"]
    return segments[1] if len(segments) > 1 else ""


def _module_names(groups: dict[str, list[Object]]) -> dict[str, str]:
    """A module per group, lower-cased, made unique and kept off Python keywords."""
    names: dict[str, str] = {}
    taken: set[str] = set()
    for group in sorted(groups, key=lambda g: (g != "", g)):
        base = re.sub(r"[^a-z0-9_]", "_", group.lower()) or "root"
        if group == "":
            base = next(iter(groups[""])).path.rstrip(".").lower() if groups[""] else "root"
        name = base + "_" if keyword.iskeyword(base) else base
        while name in taken:
            name += "_"
        taken.add(name)
        names[group] = name
    return names


def _postorder(objects: list[Object]) -> list[Object]:
    """Deepest objects first, so every class is defined before the class that holds it."""
    return sorted(objects, key=lambda o: -o.path.count("."))


def class_name(obj: Object, root: str) -> str:
    segments = [s for s in obj.path.rstrip(".").split(".") if s != "{i}"]
    return root if len(segments) == 1 else "_".join(segments[1:])


def _imports(objects: list[Object]) -> str:
    types = {_PY_TYPE[p.syntax.base_type] for o in objects for p in o.parameters.values()}
    lines = [
        "from typing import Annotated as _Annotated, ClassVar as _ClassVar, Literal as _Literal\n"
    ]
    if "_datetime" in types:
        lines.append("from datetime import datetime as _datetime\n")
    if "_Decimal" in types:
        lines.append("from decimal import Decimal as _Decimal\n")
    lines.append("from pydantic import Field as _Field\n")
    lines.append("from bbfmodels.ir import BaseType as _BaseType\n")
    helpers = sorted(t for t in types if t in ("_Boolean", "_HexBinary", "_Base64Binary"))
    names = ["CommaList as _CommaList", "Model as _Model", "Param as _Param"]
    names += [f"{h[1:]} as {h}" for h in helpers]
    lines.append("from bbfmodels.model import " + ", ".join(names) + "\n\n\n")
    return "".join(lines)


def _emit_class(obj: Object, root: str, package: str, modules: dict[str, str], model: Model) -> str:
    name = class_name(obj, root)
    if name in obj.parameters or any(
        class_name(c, root) in obj.parameters for c in _children(obj, model)
    ):
        raise ValueError(f"{obj.path} has a parameter named like a generated class")
    lines = [f"class {name}(_Model):\n"]
    lines.append(f'    bbf_path: _ClassVar[str] = "{obj.path}"\n')
    lines.append(f'    bbf_package: _ClassVar[str] = "{package}"\n')
    for param in obj.parameters.values():
        lines.append(_emit_parameter(param))
    for child in _children(obj, model):
        child_name = class_name(child, root)
        group = _group_of(child, root)
        ref = child_name if _group_of(obj, root) == group else f"{modules[group]}.{child_name}"
        field = _field_name(child.name)
        alias = f', alias="{child.name}"' if field != child.name else ""
        if child.multi_instance:
            lines.append(f"    {field}: dict[int, {ref}] = _Field(default_factory=dict{alias})\n")
        else:
            lines.append(f"    {field}: {ref} | None = _Field(default=None{alias})\n")
    lines.append("\n\n")
    return "".join(lines)


def _children(obj: Object, model: Model) -> list[Object]:
    return [o for o in model.objects.values() if o.parent_path == obj.path]


def _field_name(name: str) -> str:
    return name + "_" if name in _RESERVED or name.startswith("model_") else name


def _emit_parameter(param: Parameter) -> str:
    s = param.syntax
    py = _PY_TYPE[s.base_type]
    if (
        s.base_type is BaseType.STRING
        and s.facets.enumerations
        and s.facets.enumeration_ref is None
    ):
        values = ", ".join(repr(e.value) for e in s.facets.enumerations)
        py = f"_Literal[{values}] | str"
    if s.list is not None:
        py = f"_CommaList[{py}]"
    meta = f"_Param(_BaseType.{s.base_type.name}" + (", list=True)" if s.list is not None else ")")
    field = _field_name(param.name)
    default = f'_Field(default=None, alias="{param.name}")' if field != param.name else "None"
    return f"    {field}: _Annotated[{py} | None, {meta}] = {default}\n"


def write_package(package: str, document: Path, root: Path) -> list[Path]:
    """Generate ``package`` from ``document`` under the source root ``root`` (``src/``)."""
    from bbfmodels.parser import parse_file

    out = root.joinpath(*package.split("."))
    return generate(parse_file(document), package, out)
