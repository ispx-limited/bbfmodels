# Every helper is imported under a leading-underscore alias because a
# parameter may carry the helper's name (TR-181 has one called ``Param``)
# and a class body resolves names against the fields defined above the
# annotation. Forum names never start with an underscore.
_PY_TYPE = {
    BaseType.STRING: "str",
    BaseType.INT: "int",
    BaseType.UNSIGNED_INT: "int",
    BaseType.LONG: "int",
    BaseType.UNSIGNED_LONG: "int",
    BaseType.BOOLEAN: "_Boolean",
    BaseType.DATE_TIME: "_datetime",
    BaseType.HEX_BINARY: "_HexBinary",
    BaseType.BASE64: "_Base64Binary",
    BaseType.DECIMAL: "_Decimal",
}

# Names a field cannot have: the base class uses them, Python reserves them,
# or pydantic reads them from the class body (``Config`` is its legacy
# configuration class, and TR-181 has tables called ``Config``).
_RESERVED = set(dir(BaseModel)) | {"Config"} | set(keyword.kwlist)

# The header names the source document and not the tool version: the version
# changes with every release and would make every generated file stale on
# the release tag.
_HEADER = (
    "# Generated by bbfmodels from {source}. Do not edit: change the generator\n"
    "# or the source document and regenerate.\n"
    "# ruff: noqa\n\n"
)


def generate(doc: Document, package: str, out: Path) -> list[Path]:
    """Write the package for a document's root model into ``out``; returns the files written."""
    model = _root_model(doc)
    # The root class is named after the root object, not the model: a vendor
    # document may call its model ``InternetGatewayDevice_9.5.0:2.0`` while
    # its root object is still ``InternetGatewayDevice.``.
    root = next(iter(model.objects.values())).name
    source = doc.file or doc.spec
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    groups: dict[str, list[Object]] = {}
    for obj in model.objects.values():
        groups.setdefault(_group_of(obj, root), []).append(obj)
    modules = _module_names(groups)

    for group, objects in groups.items():
        if group == "":
            continue
        body = _HEADER.format(source=source) + _imports(objects)
        body += "".join(_emit_class(o, root, package, modules, model) for o in _postorder(objects))
        body += _emit_arguments(objects, root, package)
        path = out / f"{modules[group]}.py"
        path.write_text(body)
        written.append(path)

    root_objects = groups.get("", [])
    body = _HEADER.format(source=source) + _imports(root_objects)
    body += "".join(f"from {package} import {modules[g]}\n" for g in sorted(groups) if g != "")
    body += "\n"
    body += "".join(_emit_class(o, root, package, modules, model) for o in _postorder(root_objects))
    body += _emit_arguments(root_objects, root, package)
    others = [modules[g] for g in sorted(groups) if g != ""]
    body += "# Every command's input and output class, and every event's class, by path.\n"
    body += "COMMANDS = {" + "".join(f"**{m}.COMMANDS, " for m in others) + "**_COMMANDS}\n"
    body += "EVENTS = {" + "".join(f"**{m}.EVENTS, " for m in others) + "**_EVENTS}\n"
    root_path = out / f"{modules['']}.py"
    root_path.write_text(body)
    written.append(root_path)

    paths_py = out / "paths.py"
    paths_py.write_text(_emit_paths_module(model, root, package, source))
    written.append(paths_py)
    paths_pyi = out / "paths.pyi"
    paths_pyi.write_text(_emit_paths_stub(model, root, source))
    written.append(paths_pyi)

    init = (
        f'"""{model.name} from {source}.\n\n'
        f"Generated by bbfmodels. Do not edit: change the generator or the source\n"
        f"document and regenerate. ``schema()`` loads the IR the models were\n"
        f'generated from, for validation and descriptions.\n"""\n\n'
        f"from bbfmodels.model import load_schema\n"
        f"from {package}.{modules['']} import COMMANDS, EVENTS, {identifier(root)}\n\n"
        f'SOURCE = "{source}"\n'
        f'SPEC = "{doc.spec}"\n'
        f'MODEL = "{model.name}"\n\n\n'
        f"def schema():  # type: ignore[no-untyped-def]\n"
        f"    return load_schema(__name__)\n\n\n"
        f'__all__ = ["{identifier(root)}", "COMMANDS", "EVENTS", "MODEL", "SOURCE", "SPEC", '
        f'"schema"]\n'
    )
    init_path = out / "__init__.py"
    init_path.write_text(init)
    written.append(init_path)

    ir_path = out / "ir.json.gz"
    ir_path.write_bytes(gzip.compress(doc.model_dump_json(exclude_defaults=True).encode(), mtime=0))
    written.append(ir_path)
    return written


def _root_model(doc: Document) -> Model:
    """The one model a package is generated from, root or service.

    A service model's root object is a table (``VoiceService.{i}.``) that a
    device mounts under its ``Services.`` object; the package is generated
    as the document writes it and the mount is given when converting.
    """
    if len(doc.models) != 1:
        raise ValueError(
            f"{doc.file or doc.spec} has {len(doc.models)} models; "
            "one package is generated per model"
        )
    return doc.models[0]


def _group_of(obj: Object, root: str) -> str:
    segments = [s for s in obj.path.rstrip(".").split(".") if s != "{i}"]
    return segments[1] if len(segments) > 1 else ""


def _module_names(groups: dict[str, list[Object]]) -> dict[str, str]:
    """A module per group, lower-cased, made unique and kept off Python keywords."""
    names: dict[str, str] = {}
    taken: set[str] = set()
    for group in sorted(groups, key=lambda g: (g != "", g)):
        base = identifier(group).lower() if group else "root"
        if group == "":
            root = groups[""][0] if groups[""] else None
            base = class_name(root, root.name).lower() if root else "root"
        name = base + "_" if keyword.iskeyword(base) else base
        while name in taken:
            name += "_"
        taken.add(name)
        names[group] = name
    return names


def _postorder(objects: list[Object]) -> list[Object]:
    """Deepest objects first, so every class is defined before the class that holds it."""
    return sorted(objects, key=lambda o: -o.path.count("."))


def class_name(obj: Object, root: str) -> str:
    segments = [s for s in obj.path.rstrip(".").split(".") if s != "{i}"]
    return identifier(root) if len(segments) == 1 else identifier("_".join(segments[1:]))


def _all_parameters(objects: list[Object]) -> list[Parameter]:
    out: list[Parameter] = []

    def args(a: Arguments) -> None:
        out.extend(a.parameters.values())
        for nested in a.objects.values():
            out.extend(nested.parameters.values())

    for o in objects:
        out.extend(o.parameters.values())
        for c in o.commands.values():
            args(c.input)
            args(c.output)
        for e in o.events.values():
            args(e.arguments)
    return out


def _imports(objects: list[Object]) -> str:
    types = {_PY_TYPE[p.syntax.base_type] for p in _all_parameters(objects)}
    lines = ["from typing import Annotated as _Annotated, Literal as _Literal\n"]
    if "_datetime" in types:
        lines.append("from datetime import datetime as _datetime\n")
    if "_Decimal" in types:
        lines.append("from decimal import Decimal as _Decimal\n")
    lines.append("from pydantic import Field as _Field\n")
    lines.append("from bbfmodels.ir import BaseType as _BaseType\n")
    helpers = sorted(t for t in types if t in ("_Boolean", "_HexBinary", "_Base64Binary"))
    names = ["CommaList as _CommaList", "Model as _Model", "Param as _Param"]
    names += [f"{h[1:]} as {h}" for h in helpers]
    lines.append("from bbfmodels.model import " + ", ".join(names) + "\n\n\n")
    return "".join(lines)


def _emit_class(obj: Object, root: str, package: str, modules: dict[str, str], model: Model) -> str:
    name = class_name(obj, root)
    if name in obj.parameters or any(
        class_name(c, root) in obj.parameters for c in _children(obj, model)
    ):
        raise ValueError(f"{obj.path} has a parameter named like a generated class")
    lines = [f"class {name}(_Model):\n"]
    lines.append(f'    __bbf_path__ = "{obj.path}"\n')
    lines.append(f'    __bbf_package__ = "{package}"\n')
    for param in obj.parameters.values():
        lines.append(_emit_parameter(param))
    for child in _children(obj, model):
        child_name = class_name(child, root)
        group = _group_of(child, root)
        ref = child_name if _group_of(obj, root) == group else f"{modules[group]}.{child_name}"
        field = _field_name(child.name)
        alias = f', alias="{child.name}"' if field != child.name else ""
        if child.multi_instance:
            lines.append(f"    {field}: dict[int, {ref}] = _Field(default_factory=dict{alias})\n")
        else:
            lines.append(f"    {field}: {ref} | None = _Field(default=None{alias})\n")
    lines.append("\n\n")
    return "".join(lines)


def _children(obj: Object, model: Model) -> list[Object]:
    return [o for o in model.objects.values() if o.parent_path == obj.path]


def _field_name(name: str) -> str:
    field = identifier(name)
    return field + "_" if field in _RESERVED or field.startswith("model_") else field


def _emit_parameter(param: Parameter) -> str:
    s = param.syntax
    py = _PY_TYPE[s.base_type]
    if (
        s.base_type is BaseType.STRING
        and s.facets.enumerations
        and s.facets.enumeration_ref is None
    ):
        values = ", ".join(repr(e.value) for e in s.facets.enumerations)
        py = f"_Literal[{values}] | str"
    if s.list is not None:
        py = f"_CommaList[{py}]"
    meta = f"_Param(_BaseType.{s.base_type.name}" + (", list=True)" if s.list is not None else ")")
    field = _field_name(param.name)
    default = f'_Field(default=None, alias="{param.name}")' if field != param.name else "None"
    return f"    {field}: _Annotated[{py} | None, {meta}] = {default}\n"


def write_package(package: str, document: Path, root: Path) -> list[Path]:
    """Generate ``package`` from ``document`` under the source root ``root`` (``src/``)."""
    from bbfmodels.parser import parse_file

    out = root.joinpath(*package.split("."))
    return generate(parse_file(document), package, out)


_STUB_TYPE = {
    BaseType.STRING: "str",
    BaseType.INT: "int",
    BaseType.UNSIGNED_INT: "int",
    BaseType.LONG: "int",
    BaseType.UNSIGNED_LONG: "int",
    BaseType.BOOLEAN: "bool",
    BaseType.DATE_TIME: "datetime",
    BaseType.HEX_BINARY: "bytes",
    BaseType.BASE64: "bytes",
    BaseType.DECIMAL: "Decimal",
}


def _emit_paths_module(model: Model, root: str, package: str, source: str) -> str:
    """The runtime half of typed paths: one root object over the package's schema."""
    root_obj = next(iter(model.objects.values()))
    kind = "TablePath" if root_obj.multi_instance else "ObjectPath"
    data = root_obj.path.replace("{i}.", "")
    return (
        _HEADER.format(source=source)
        + "from bbfmodels.model import load_schema as _load_schema\n"
        + f"from bbfmodels.paths import {kind} as _{kind}\n\n\n"
        + "def _schema():  # type: ignore[no-untyped-def]\n"
        + f'    return _load_schema("{package}")\n\n\n'
        + f'{identifier(root)} = _{kind}(_schema, "{data}", "{root_obj.path}")\n'
    )


def _emit_paths_stub(model: Model, root: str, source: str) -> str:
    """The stub editors read: a class per object with every name and value type."""
    lines = [
        _HEADER.format(source=source),
        "from datetime import datetime\n",
        "from decimal import Decimal\n",
        "from bbfmodels.paths import CommandPath, EventPath, ObjectPathBase, ParamPath, "
        "TablePath\n\n",
    ]
    for obj in _postorder(list(model.objects.values())):
        name = class_name(obj, root) + "Path"
        lines.append(f"class {name}(ObjectPathBase):\n")
        for param in obj.parameters.values():
            s = param.syntax
            value = _STUB_TYPE[s.base_type]
            if s.list is not None:
                value = f"list[{value}]"
            lines.append(f"    {identifier(param.name)}: ParamPath[{value}]\n")
        for child in _children(obj, model):
            child_name = class_name(child, root) + "Path"
            field = identifier(child.name)
            if child.multi_instance:
                lines.append(f"    {field}: TablePath[{child_name}]\n")
            else:
                lines.append(f"    {field}: {child_name}\n")
        taken = {identifier(n) for n in obj.parameters} | {
            identifier(c.name) for c in _children(obj, model)
        }
        for cmd in obj.commands.values():
            lines.append(f"    {_member_identifier(cmd.name, taken)}: CommandPath\n")
        for ev in obj.events.values():
            lines.append(f"    {_member_identifier(ev.name, taken)}: EventPath\n")
        if not obj.parameters and not _children(obj, model) and not obj.commands and not obj.events:
            lines.append("    pass\n")
        lines.append("\n")
    root_obj = next(iter(model.objects.values()))
    root_name = class_name(root_obj, root) + "Path"
    if root_obj.multi_instance:
        lines.append(f"{identifier(root)}: TablePath[{root_name}]\n")
    else:
        lines.append(f"{identifier(root)}: {root_name}\n")
    return "".join(lines)


def _emit_arguments(objects: list[Object], root: str, package: str) -> str:
    """Classes for every command's input and output and every event's payload.

    A command ``Device.IP.Diagnostics.TraceRoute()`` becomes
    ``IP_Diagnostics_TraceRoute_Input`` and ``IP_Diagnostics_TraceRoute_Output``;
    an object inside the output, ``RouteHops.{i}.``, becomes
    ``IP_Diagnostics_TraceRoute_Output_RouteHops`` held as a table. Their
    schema paths are the ones the schema indexes arguments under. The module
    ends with the registries the root module merges.
    """
    out: list[str] = []
    commands: list[str] = []
    events: list[str] = []
    for obj in objects:
        owner = class_name(obj, root)
        for cmd in obj.commands.values():
            base = f"{owner}_{identifier(member_name(cmd.name))}"
            inp = _emit_argument_classes(
                f"{base}_Input", f"{obj.path}{cmd.name}.Input.", cmd.input, package, out
            )
            outp = _emit_argument_classes(
                f"{base}_Output", f"{obj.path}{cmd.name}.Output.", cmd.output, package, out
            )
            commands.append(f'    "{obj.path}{cmd.name}": ({inp}, {outp}),\n')
        for ev in obj.events.values():
            name = f"{owner}_{identifier(member_name(ev.name))}_Event"
            cls = _emit_argument_classes(name, f"{obj.path}{ev.name}.", ev.arguments, package, out)
            events.append(f'    "{obj.path}{ev.name}": {cls},\n')
    out.append(
        "_COMMANDS: dict[str, tuple[type[_Model], type[_Model]]] = {\n" + "".join(commands) + "}\n"
    )
    out.append("_EVENTS: dict[str, type[_Model]] = {\n" + "".join(events) + "}\n")
    out.append("COMMANDS = _COMMANDS\nEVENTS = _EVENTS\n\n")
    return "".join(out)


def _emit_argument_classes(
    name: str, path: str, args: Arguments, package: str, out: list[str]
) -> str:
    """Emit one argument set's class and the classes of the objects inside it, deepest first."""
    nested = sorted(args.objects.items(), key=lambda kv: -kv[0].count("."))
    for rel, obj in nested:
        segments = [s for s in rel.rstrip(".").split(".") if s != "{i}"]
        lines = [f"class {name}_{'_'.join(identifier(s) for s in segments)}(_Model):\n"]
        lines.append(f'    __bbf_path__ = "{path}{rel}"\n')
        lines.append(f'    __bbf_package__ = "{package}"\n')
        for param in obj.parameters.values():
            lines.append(_emit_parameter(param))
        lines.extend(_emit_nested_children(name, rel, args))
        out.append("".join(lines) + "\n\n")
    lines = [f"class {name}(_Model):\n"]
    lines.append(f'    __bbf_path__ = "{path}"\n')
    lines.append(f'    __bbf_package__ = "{package}"\n')
    for param in args.parameters.values():
        lines.append(_emit_parameter(param))
    lines.extend(_emit_nested_children(name, "", args))
    out.append("".join(lines) + "\n\n")
    return name


def _emit_nested_children(name: str, rel: str, args: Arguments) -> list[str]:
    """Fields for the argument objects directly under ``rel``; ``""`` is the argument set itself."""
    lines: list[str] = []
    for child_rel in args.objects:
        parent = child_rel[:-4] if child_rel.endswith("{i}.") else child_rel
        parent = parent.rstrip(".").rpartition(".")[0]
        parent = parent + "." if parent else ""
        if parent != rel:
            continue
        segments = [s for s in child_rel.rstrip(".").split(".") if s != "{i}"]
        cls = f"{name}_{'_'.join(identifier(s) for s in segments)}"
        field = _field_name(segments[-1])
        alias = f', alias="{segments[-1]}"' if field != segments[-1] else ""
        if child_rel.endswith("{i}."):
            lines.append(f"    {field}: dict[int, {cls}] = _Field(default_factory=dict{alias})\n")
        else:
            lines.append(f"    {field}: {cls} | None = _Field(default=None{alias})\n")
    return lines


def _member_identifier(forum: str, taken: set[str]) -> str:
    """The attribute a command or event is reached by in a path.

    The bare name, ``Reboot`` for ``Reboot()``, unless a parameter or child
    object already has it (Matter has ``ValveFault`` beside ``ValveFault!``),
    in which case a trailing underscore tells them apart. The runtime
    applies the same rule.
    """
    name = identifier(member_name(forum))
    if name in taken:
        name += "_"
    taken.add(name)
    return name
