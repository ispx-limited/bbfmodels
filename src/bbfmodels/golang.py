"""Go types for a document's model, emitted from the IR.

One Go package per document: a struct per object named like the generated
Python class (``WiFi_Radio``), a pointer field per parameter so an absent
value is ``nil`` and ``omitempty`` leaves it out, a child object as a
pointer to its struct, a table as ``map[int]*Child`` keyed by instance
number (``encoding/json`` writes and reads integer keys as strings, which
is how a table serialises). Every field carries a ``json`` tag with the
Forum's name and a ``bbf`` tag with the schema path, so a Go program can
walk a struct's tags to build the data paths it asks an ACS for.

Command inputs and outputs and event payloads are structs too. The output
is split like the Python package, one file per top-level subtree, each
beginning with the package clause, so a document generates straight into
a directory a Go module can import. The layout is one gofmt leaves
unchanged; the test suite runs gofmt and go vet over the result when a Go
toolchain is present.
"""

from __future__ import annotations

import re
from pathlib import Path

from bbfmodels.generate import class_name
from bbfmodels.ir import Arguments, BaseType, Document, Model, Object, Parameter, Syntax
from bbfmodels.paths import identifier, member_name

_GO_TYPE = {
    BaseType.STRING: "string",
    BaseType.INT: "int32",
    BaseType.UNSIGNED_INT: "uint32",
    BaseType.LONG: "int64",
    BaseType.UNSIGNED_LONG: "uint64",
    BaseType.BOOLEAN: "bool",
    BaseType.DATE_TIME: "time.Time",
    BaseType.HEX_BINARY: "string",
    BaseType.BASE64: "string",
    BaseType.DECIMAL: "float64",
}

# Any punctuation other than parentheses and commas, which gofmt allows in a heading.
_PUNCTUATION = re.compile(r"[^\w\s(),\u201c\u201d'\"-]")

_HEADER = (
    "// Code generated by bbfmodels from {source}. DO NOT EDIT.\n"
    "// Change the generator or the source document and regenerate.\n\n"
    "package {package}\n\n"
)


def go_package(doc: Document, package: str, *, descriptions: bool = True) -> dict[str, str]:
    """The Go source files of a document's model, by file name."""
    if len(doc.models) != 1:
        raise ValueError(
            f"{doc.file or doc.spec} has {len(doc.models)} models; one package per model"
        )
    if not re.fullmatch(r"[a-z][a-z0-9_]*", package):
        raise ValueError(
            f"{package!r} is not a Go package name (lower case letters, digits, underscores)"
        )
    model = doc.models[0]
    root_obj = next(iter(model.objects.values()))
    root = root_obj.name
    em = _Emitter(model, root, descriptions)
    groups: dict[str, list[Object]] = {}
    for obj in model.objects.values():
        groups.setdefault(_group_of(obj), []).append(obj)
    source = doc.file or doc.spec
    files: dict[str, str] = {}
    for group, objects in groups.items():
        body: list[str] = []
        for obj in objects:
            body.append(em.struct(class_name(obj, root), obj, obj.path))
            em.arguments(obj, root, body)
        text = "".join(body).rstrip("\n") + "\n"
        name = (identifier(group).lower() if group else class_name(root_obj, root).lower()) + ".go"
        files[name] = _HEADER.format(source=source, package=package) + _imports(text) + text
    doc_go = (
        f"// Package {package} holds the {model.name} data model from {source},\n"
        f"// generated by bbfmodels (https://github.com/ispx-limited/bbfmodels).\n"
        f"//\n"
        f"// Every field is a pointer or a map so an absent value is nil, a table is a\n"
        f"// map keyed by instance number, and each field's bbf tag is its schema path.\n"
        f"package {package}\n"
    )
    files["doc.go"] = doc_go
    return files


def write_go_package(
    doc: Document, package: str, out: Path, *, descriptions: bool = True
) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in go_package(doc, package, descriptions=descriptions).items():
        path = out / name
        path.write_text(text)
        written.append(path)
    return written


def _group_of(obj: Object) -> str:
    segments = [s for s in obj.path.rstrip(".").split(".") if s != "{i}"]
    return segments[1] if len(segments) > 1 else ""


def _imports(text: str) -> str:
    return 'import "time"\n\n' if "time.Time" in text else ""


def _field_name(name: str) -> str:
    field = identifier(name)
    return field[0].upper() + field[1:]


class _Emitter:
    def __init__(self, model: Model, root: str, descriptions: bool) -> None:
        self.model = model
        self.root = root
        self.descriptions = descriptions

    def comment(self, text: str, indent: str = "") -> str:
        if not text:
            return ""
        # gofmt rewrites the Forum's '' and `` quote pairs in doc comments to
        # typographic quotes; writing them that way keeps the output gofmt-clean.
        text = text.replace("``", "\u201c").replace("''", "\u201d")
        paragraphs = text.split("\n\n")
        for i, para in enumerate(paragraphs[:-1]):
            # gofmt promotes a one-line paragraph with no punctuation that is
            # followed by another paragraph to a heading. A full stop keeps it
            # a sentence, which is what the Forum meant.
            if "\n" not in para and para[:1].isupper() and not _PUNCTUATION.search(para):
                paragraphs[i] = para + "."
        text = "\n\n".join(paragraphs)
        return "".join(f"{indent}// {line}".rstrip() + "\n" for line in text.split("\n"))

    def struct(
        self,
        name: str,
        obj: Object,
        path: str,
        children: list[tuple[str, str, bool]] | None = None,
    ) -> str:
        if children is None:
            children = [
                (c.name, class_name(c, self.root), c.multi_instance)
                for c in self.model.objects.values()
                if c.parent_path == path
            ]
        head = f"{name} is {path}"
        if self.descriptions and obj.description:
            head += "\n\n" + obj.description
        lines = [self.comment(head), f"type {name} struct {{\n"]
        rows: list[tuple[str, str, str, str]] = []
        for param in obj.parameters.values():
            rows.append(self.field(param, path))
        for child_name, child_type, multi in children:
            typ = f"map[int]*{child_type}" if multi else f"*{child_type}"
            rows.append(
                (
                    "",
                    _field_name(child_name),
                    typ,
                    f'`json:"{child_name},omitempty" bbf:"{path}{child_name}."`',
                )
            )
        lines.append(_align(rows))
        lines.append("}\n\n")
        return "".join(lines)

    def field(self, param: Parameter, path: str) -> tuple[str, str, str, str]:
        notes = []
        if param.access is not None:
            notes.append(param.access.value)
        if param.status.value != "current":
            notes.append(param.status.value)
        if param.mandatory:
            notes.append("mandatory")
        text = ", ".join(notes)
        if self.descriptions and param.description:
            text = f"{text}. {param.description}" if text else param.description
        typ = self.type_of(param.syntax)
        tag = f'`json:"{param.name},omitempty" bbf:"{path}{param.name}"`'
        return (self.comment(text, "\t"), _field_name(param.name), typ, tag)

    def type_of(self, s: Syntax) -> str:
        base = _GO_TYPE[s.base_type]
        return f"[]{base}" if s.list is not None else f"*{base}"

    def arguments(self, obj: Object, root: str, out: list[str]) -> None:
        owner = class_name(obj, root)
        for cmd in obj.commands.values():
            base = f"{owner}_{identifier(member_name(cmd.name))}"
            path = f"{obj.path}{cmd.name}"
            self.argument_structs(f"{base}_Input", f"{path}.Input.", cmd.input, out)
            self.argument_structs(f"{base}_Output", f"{path}.Output.", cmd.output, out)
        for ev in obj.events.values():
            name = f"{owner}_{identifier(member_name(ev.name))}_Event"
            self.argument_structs(name, f"{obj.path}{ev.name}.", ev.arguments, out)

    def argument_structs(self, name: str, path: str, args: Arguments, out: list[str]) -> None:
        def children_of(rel: str) -> list[tuple[str, str, bool]]:
            found = []
            for child_rel in args.objects:
                parent = child_rel[:-4] if child_rel.endswith("{i}.") else child_rel
                parent = parent.rstrip(".").rpartition(".")[0]
                parent = parent + "." if parent else ""
                if parent == rel:
                    segments = [s for s in child_rel.rstrip(".").split(".") if s != "{i}"]
                    found.append(
                        (
                            segments[-1],
                            f"{name}_{'_'.join(identifier(s) for s in segments)}",
                            child_rel.endswith("{i}."),
                        )
                    )
            return found

        for rel, nested in args.objects.items():
            segments = [s for s in rel.rstrip(".").split(".") if s != "{i}"]
            out.append(
                self.struct(
                    f"{name}_{'_'.join(identifier(s) for s in segments)}",
                    nested,
                    path + rel,
                    children_of(rel),
                )
            )
        out.append(
            self.struct(name, Object(path=path, parameters=args.parameters), path, children_of(""))
        )


def _align(rows: list[tuple[str, str, str, str]]) -> str:
    """Struct fields in the layout gofmt leaves alone.

    gofmt aligns consecutive fields into columns, with rules about which
    comment lines break a run that are not worth reproducing. A blank line
    between fields ends every run, so each field stands on its own with
    single spaces and its doc comment above it, which is also how hand
    written Go with a comment per field reads.
    """
    return "\n".join(f"{comment}\t{name} {typ} {tag}\n" for comment, name, typ, tag in rows)
