"""Assemble the Go module and the npm package from the shipped documents.

Both are built from the same pinned documents as the Python packages and
carry the bbfmodels version. ``go_module`` writes a Go module tree, one
package per document, with ``go.mod``, README, licence and notice, ready
to be committed to the ``bbfmodels-go`` repository and tagged.
``npm_package`` writes an npm package of TypeScript declarations, one
module per document exposed as a subpath export (``bbfmodels/tr181_usp``),
ready for ``npm publish``. The release workflow calls both; a person can
call them locally through ``bbfmodels distribute``.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from bbfmodels import __version__, sources
from bbfmodels.generate import PACKAGES
from bbfmodels.golang import write_go_package
from bbfmodels.parser import parse_file
from bbfmodels.typescript import declarations

GO_MODULE = "github.com/ispx-limited/bbfmodels-go"
NPM_NAME = "bbfmodels"
_REPO_ROOT = Path(__file__).resolve().parents[2]


def _short(package: str) -> str:
    return package.rpartition(".")[2]


def go_package_name(package: str) -> str:
    """The Go package for a shipped Python package: ``tr181usp`` for ``bbfmodels.tr181_usp``."""
    return _short(package).replace("_", "")


def go_module(out: Path, version: str = __version__, root: Path = _REPO_ROOT) -> list[Path]:
    """The Go module tree: a package per document, ``go.mod``, README, LICENSE and NOTICE."""
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for package, name in PACKAGES.items():
        target = out / go_package_name(package)
        if target.exists():
            shutil.rmtree(target)
        written += write_go_package(
            parse_file(sources.fetch(name)), go_package_name(package), target
        )
    (out / "go.mod").write_text(f"module {GO_MODULE}\n\ngo 1.22\n")
    packages = ", ".join(f"`{go_package_name(p)}`" for p in PACKAGES)
    (out / "README.md").write_text(
        "# bbfmodels-go\n\n"
        "Go types for the Broadband Forum's data models, generated by\n"
        "[bbfmodels](https://github.com/ispx-limited/bbfmodels) on every release.\n"
        "Nothing here is edited by hand: the bbfmodels release workflow regenerates\n"
        "every package from the Forum's published documents and tags this repository\n"
        f"with the same version. This is bbfmodels {version}.\n\n"
        "```go\n"
        f'import "{GO_MODULE}/tr181usp"\n\n'
        "var device tr181usp.Device\n"
        "json.Unmarshal(body, &device)\n"
        "*device.WiFi.Radio[1].Channel // 36\n"
        "```\n\n"
        f"One package per document: {packages}.\n\n"
        "A struct per object, a pointer field per parameter, a table as a map keyed by\n"
        "instance number, and `json` and `bbf` tags carrying the Forum's name and the\n"
        "schema path. The [Go guide](https://docs.bbfmodels.ispx.co/guides/go/) has the\n"
        "details; issues and changes go to bbfmodels.\n\n"
        "Apache-2.0, copyright ISPX LIMITED. The Broadband Forum publishes its data\n"
        "models under the BSD 3-clause licence; see NOTICE.\n"
    )
    written += [*_notices(out, root), out / "go.mod", out / "README.md"]
    return written


def npm_package(out: Path, version: str = __version__, root: Path = _REPO_ROOT) -> list[Path]:
    """The npm package: a ``.d.ts`` per document as a subpath export, plus ``package.json``."""
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    exports: dict[str, dict[str, str]] = {}
    for package, name in PACKAGES.items():
        short = _short(package)
        path = out / f"{short}.d.ts"
        path.write_text(declarations(parse_file(sources.fetch(name))))
        exports[f"./{short}"] = {"types": f"./{short}.d.ts"}
        written.append(path)
    manifest = {
        "name": NPM_NAME,
        "version": version,
        "description": (
            "TypeScript declarations for Broadband Forum data models (TR-181, TR-098, TR-104 "
            "and more), generated from the published XML"
        ),
        "license": "Apache-2.0",
        "author": "ISPX LIMITED",
        "repository": {"type": "git", "url": "git+https://github.com/ispx-limited/bbfmodels.git"},
        "homepage": "https://docs.bbfmodels.ispx.co/guides/typescript/",
        "bugs": "https://github.com/ispx-limited/bbfmodels/issues",
        "keywords": [
            "tr-069",
            "tr-181",
            "tr-098",
            "tr-369",
            "usp",
            "cwmp",
            "broadband-forum",
            "typescript",
        ],
        "exports": exports,
        "files": ["*.d.ts", "README.md", "LICENSE", "NOTICE"],
        "sideEffects": False,
    }
    (out / "package.json").write_text(json.dumps(manifest, indent=2) + "\n")
    modules = ", ".join(f"`bbfmodels/{_short(p)}`" for p in PACKAGES)
    (out / "README.md").write_text(
        "# bbfmodels\n\n"
        "TypeScript declarations for the Broadband Forum's data models, generated by\n"
        "[bbfmodels](https://github.com/ispx-limited/bbfmodels) from the XML the Forum\n"
        f"publishes. This is bbfmodels {version}. Types only: there is no runtime code.\n\n"
        "```ts\n"
        'import type { Root, WiFi_Radio, Commands } from "bbfmodels/tr181_usp";\n\n'
        "const radio: WiFi_Radio = { Enable: true, Channel: 36, "
        'OperatingChannelBandwidth: "80MHz" };\n'
        "const device: Root = { WiFi: { Radio: { 1: radio } } };\n"
        'type TraceRoute = Commands["Device.IP.Diagnostics.TraceRoute()"]["output"];\n'
        "```\n\n"
        f"One module per document: {modules}.\n\n"
        "An interface per object, an optional property per parameter, a table as\n"
        "`Instances<Child>`, enumerations as `Open<...>` so the editor completes the\n"
        "Forum's values while any string type checks, and vendor `X_` members admitted.\n"
        "The [TypeScript guide](https://docs.bbfmodels.ispx.co/guides/typescript/) has\n"
        "the details; issues and changes go to bbfmodels.\n\n"
        "Apache-2.0, copyright ISPX LIMITED. The Broadband Forum publishes its data\n"
        "models under the BSD 3-clause licence; see NOTICE.\n"
    )
    written += [*_notices(out, root), out / "package.json", out / "README.md"]
    return written


def _notices(out: Path, root: Path) -> list[Path]:
    written = []
    for name in ("LICENSE", "NOTICE"):
        source = root / name
        if source.exists():
            shutil.copy(source, out / name)
            written.append(out / name)
    return written
